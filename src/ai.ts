// ─── Build Full System Prompt ────────────────────────────────────────────────

export function buildSystemPrompt(
  mood: MoodData,
  profile: UserProfile,
  userName: string,
  chatType: "private" | "group" | "supergroup" | "channel",
  chatId: number,
  options?: { missedMessages?: number },
): string {
  let prompt = BASE_PERSONALITY + "\n\n";

  // Time of day
  prompt += timeOfDayBlock() + "\n\n";

  // Mood
  prompt += moodBlock(mood) + "\n\n";

  // Relationship
  const relationshipInfo = buildRelationshipSummary(profile);
  prompt += relationshipInfo + "\n\n";

  // Rules
  prompt += RULES + "\n\n";

  // Chat type specific
  if (chatType === "private") {
    prompt += privateChatBlock();
  } else {
    prompt += groupChatBlock();

    if (chatId === VIP_GROUP_ID) {
      prompt += "\n\n" + vipMemberRegistryBlock();
      prompt += "\n\n" + amonyaAwarenessBlock();
      prompt += "\n\n" + stickerPermissionBlock();
      // Drama instinct only for playful/manic/unhinged moods
      if (["playful", "manic", "unhinged"].includes(mood.mood) && mood.intensity >= 60) {
        prompt += "\n\n" + dramaInstinctBlock();
      }
    }
  }

  // Catch-up context after blackout recovery
  if (options?.missedMessages && options.missedMessages > 0) {
    prompt += "\n\n" + catchUpBlock(options.missedMessages);
  }

  return prompt;
}

// ─── Call LLM ────────────────────────────────────────────────────────────────

export async function callLLM(
  env: Env,
  messages: LLMMessage[],
  systemPrompt: string,
  maxTokens: number = 512,
  temperature: number = 0.75,
): Promise<string | null> {
  // 1. Try Gemini
  const geminiResult = await callGemini(
    env.GEMINI_API_KEY,
    messages,
    systemPrompt,
    maxTokens,
    temperature,
  );
  if (geminiResult) return sanitizeResponse(geminiResult);

  // 2. Fallback to Workers AI
  try {
    const workersResult = await callWorkersAI(env, messages, systemPrompt, maxTokens, temperature);
    if (workersResult) return sanitizeResponse(workersResult);
  } catch (err) {
    console.error("Workers AI failed:", err);
  }

  return null;
}

